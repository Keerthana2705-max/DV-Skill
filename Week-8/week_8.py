corr = df[["math score","reading score","writing score"]].corr()

plt.imshow(corr)
plt.colorbar()
plt.xticks(range(3), ["Math","Reading","Writing"])
plt.yticks(range(3), ["Math","Reading","Writing"])

for i in range(3):
    for j in range(3):
        plt.text(j, i, f"{corr.iloc[i,j]:.2f}", ha="center")

plt.title("Correlation Heatmap")
