df["Is Renovated"] = df["yr_renovated"].apply(lambda x: "True" if x > 0 else "False")

df['price_per_sqft'] = df['price'] / df['sqft_living']
df[['price', 'sqft_living', 'price_per_sqft']].head()

df['bedrooms'] = df['bedrooms'].replace(0, np.nan)
df['bathrooms'] = df['bathrooms'].replace(0, np.nan)

df['bedrooms'] = df['bedrooms'].fillna(df['bedrooms'].median())
df['bathrooms'] = df['bathrooms'].fillna(df['bathrooms'].median())

import matplotlib.pyplot as plt
import seaborn as sns

plt.figure(figsize=(8, 5))
sns.boxplot(x=df['price'])
plt.title('Outlier Detection in House Prices')
plt.xlabel('Price')
plt.show()

plt.figure(figsize=(8, 5))
sns.boxplot(x=df['price_per_sqft'])
plt.title('Outlier Detection in Price per Square Foot')
plt.xlabel('Price per Square Foot')
plt.show()

Q1 = df['price'].quantile(0.25)
Q3 = df['price'].quantile(0.75)

IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

outliers = df[(df['price'] < lower_bound) | (df['price'] > upper_bound)]

print("Lower Bound:", lower_bound)
print("Upper Bound:", upper_bound)
print("Number of Outliers:", len(outliers))

